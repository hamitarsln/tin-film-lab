"""Write the cut list in src/film.js from a plan of holds in 16th notes:
  python3 scripts/buildedit.py docs/plan.txt

Plan lines: `<shot> <hold in 16ths> [note]`, `# comment` lines become comments in the list, blank lines are ignored.
Shots start at 1.1.1 and follow each other; the positions (bar.beat.16th) are computed, so the plan can never drift
off the grid. The list must end exactly at the stop (8.1.1), where the fixed ending (terminal, drain, end card) begins.
"""
import re, sys
plan = open(sys.argv[1]).read().splitlines()
pos16, lines = 0, []
for raw in plan:
    s = raw.strip()
    if not s:
        continue
    if s.startswith('#'):
        lines.append('  // ' + s[1:].strip()); continue
    m = re.match(r'(\S+)\s+(\d+)(?:\s+(.*))?$', s)
    if not m:
        raise SystemExit(f'bad plan line: {raw}')
    shot, hold, note = m.group(1), int(m.group(2)), (m.group(3) or '').replace("'", "\\'")
    bar, rest = divmod(pos16, 16); beat, six = divmod(rest, 4)
    lines.append(f"  ['{bar + 1}.{beat + 1}.{six + 1}', '{shot}', '{note}'],")
    pos16 += hold
if pos16 != 7 * 16:
    raise SystemExit(f'the plan fills {pos16} 16ths; it must fill exactly 112 (bars 1-7) and end at the stop, 8.1.1')
src = open('src/film.js').read()
a, b = src.index('  // EDIT:BEGIN'), src.index('  // EDIT:END')
src = src[:a] + '  // EDIT:BEGIN (generated by scripts/buildedit.py from docs/plan.txt; edit the plan, not these lines)\n' + '\n'.join(lines) + '\n' + src[b:]
open('src/film.js', 'w').write(src)
print(f'{sum(1 for l in lines if l.strip().startswith("["))} shots written before the stop')
