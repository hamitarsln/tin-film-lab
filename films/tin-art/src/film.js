// The film. seek(t) paints the frame for film time t from nothing but t: which shot (the cut list below, placed on the
// music grid of music-cut/cue.js), how far into it (push, drift, the terminal's log, the drain), the words, and grain
// seeded by the frame number. docs/EDIT.md is generated from this list by scripts/editdoc.mjs.
(() => {
const B = window.BOARD, g = B.ctx, M = Music(window.CUE), FPS = 24;
const W = B.W, H = B.H, k = W / 2160;

// ---------- the grid ----------
// 'bar.beat.16th' in film bars from 1 -> seconds. Cuts snap to the nearest frame (at most 21 ms from the beat).
const pos = p => { const [bar, beat, s = 1] = p.split('.').map(Number); return M.time(bar, beat) + (s - 1) * M.beat / 4; };
const frameOf = t => Math.round(t * FPS);

// ---------- the cut list ----------
// [position, shot, note]. Shots are still labels from src/stills.js, or the terminal and end-card states below.
// Treatments: A objects along the strokes, B material inside the mark, C material with the mark cut out as paper,
// D the mark built by the material (pixels).
const EDIT = [
  // EDIT:BEGIN (generated by scripts/buildedit.py from docs/plan.txt; edit the plan, not these lines)
  // Bars 1-2. The withhold, after Fable's (three equal holds of 24 frames, then shorter): each material pushed in slowly
  // and drifting behind the locked mark. The pressed tin Tin is named after, then the history from 1843.
  ['1.1.1', 'A2', 'prologue: the pressed tin Tin is named after'],
  ['1.3.1', '02', ''],
  ['2.1.1', '03', ''],
  ['2.3.1', '06', ''],
  ['2.4.3', 'X50', ''],
  // Bar 3, a beat each: 1900-1903
  ['3.2.1', '08', ''],
  ['3.3.1', 'X09', ''],
  ['3.4.1', '07', ''],
  // Bar 4, a beat each, then 8ths: 1900s-1930s
  ['4.1.1', 'X06', ''],
  ['4.2.1', '09', ''],
  ['4.3.1', 'X48', ''],
  ['4.3.3', '13', ''],
  ['4.4.1', '04', ''],
  ['4.4.3', '12', ''],
  // Bar 5, the beat, then every 8th as the music turns to an 8th-note pulse: the 1930s and 40s
  ['5.1.1', '11', ''],
  ['5.2.1', 'X41', ''],
  ['5.2.3', '15', ''],
  ['5.3.1', 'X51', ''],
  ['5.3.3', 'X02', ''],
  ['5.4.1', 'X10', ''],
  ['5.4.3', 'X40', ''],
  // Bar 6, every 16th, the board stills held on the bar's strong 8ths: the 1950s and 60s roadside, night and day in
  // pairs. Tonal waves (light, mid, dark and back, a reversal every two or three cuts) keep it under three flashes a second.
  ['6.1.1', '14', ''],
  ['6.1.3', 'X29', ''],
  ['6.1.4', 'X56', ''],
  ['6.2.1', 'X33', ''],
  ['6.2.2', 'X58', ''],
  ['6.2.3', 'X32', ''],
  ['6.3.1', 'X30', ''],
  ['6.3.2', 'X54', ''],
  ['6.3.3', 'X04', ''],
  ['6.3.4', 'X60', ''],
  ['6.4.1', 'X52', ''],
  ['6.4.2', 'X57', ''],
  ['6.4.3', 'X34', ''],
  ['6.4.4', 'X36', ''],
  // Bar 7: the information age, then the settle into the stop, each hold longer than the last
  ['7.1.1', '16', ''],
  ['7.1.3', 'X46', ''],
  ['7.1.4', 'X47', ''],
  ['7.2.1', 'X45', 'the settle: a screen'],
  ['7.2.3', '18', 'the 1996 banner'],
  ['7.3.3', '19', 'the 2004 search page'],
  // EDIT:END
  // The stop: the terminal arrives on the hit that starts the near-silence and holds through it, idle; "runs it."
  // and the running log enter on the hit at 8.3.4; the bass returns under it at 9.1.1.
  ['8.1.1', 'TERM', '"Your agent"; idle, the cursor blinking on the beat'],
  ['10.1.1', 'DRAIN', 'the blue drains down the frame over one beat, uncovering the end card'],
  ['10.2.1', 'END1', 'ink mark on paper, hairline grid'],
  ['11.1.1', 'END2', 'tin.computer and the lime cursor, through the fade'],
  ['11.4.1', 'END3', 'the pressed tin inside the ink mark: the loop turns it inside out'],
];
const WORDS = [['8.1.1', '8.3.4', 'Your agent'], ['8.3.4', '10.1.1', 'runs it.']];

const byLabel = l => window.STILLS.find(s => s.label === l);
const CUTS = EDIT.map(([p, shot, note], i) => ({ p, shot, note, t: pos(p), f: frameOf(pos(p)), still: byLabel(shot) }));
CUTS.forEach((c, i) => { c.fEnd = i + 1 < CUTS.length ? CUTS[i + 1].f : frameOf(M.cue.length) + 1; c.holdF = c.fEnd - c.f; });
const PUSH_PER_S = 0.045;         // the slow push on materials held a beat or longer: +4.5% a second
const PAN_PX_S = 16;              // and a slow drift behind the locked mark, px a second at 2160, direction seeded per shot
const shotAt = f => { let c = CUTS[0]; for (const x of CUTS) if (x.f <= f) c = x; return c; };

// ---------- the terminal (2026) and the end card ----------
// Drawn by src/stills.js (window.TIN), the same surfaces as board stills 20 and E. The terminal arrives on the stop:
// idle in the near-silence (the block cursor blinking on each beat, "Your agent"), then on the hit at 8.3.4 the log
// starts to run, a line per beat ("runs it."), with the bass returning under it at 9.1.1. The drain lowers the blue down
// the frame over one beat and uncovers the end card beneath it. On the film's last beat the pressed tin of the first
// frame appears inside the ink mark, so the cut back to frame 1 turns the same material inside out.
const T = () => window.TIN;
let tinTex = null;
const tinInside = async () => { tinTex = tinTex || await B.img('../materials/cut/A2-alt-tin-ceiling.png'); B.T.inside(g, tinTex); };

// ---------- the words ----------
// Opus's grammar: whole words on cuts, centred, resting on the mark's top edge; ink on the terminal's blue.
function words(text) {
  const size = 150 * k, [, top] = B.toPx(0, 174), [cx] = B.toPx(350, 0);
  g.save(); g.font = `500 ${size}px "Funktional Grotesk"`; g.fillStyle = B.INK; g.textBaseline = 'alphabetic'; g.textAlign = 'center';
  g.fillText(text, cx, top - size * 0.3); g.restore();
}

// ---------- seek ----------
let ready = null;
window.seek = async (t) => {
  await ready;
  const f = Math.max(0, Math.round(t * FPS));
  const c = shotAt(f), u = (f - c.f) / FPS, beat = M.beat;
  if (g.reset) g.reset();
  g.save();
  try {
    B.drawPaper(g);
    const m = B.motion;
    m.u = u; m.frame = f; m.drift = 1;
    const moving = c.holdF >= Math.round(beat * FPS) - 1, ang = Motion.rng(c.f * 131 + 7)() * Math.PI * 2;
    m.push = moving ? 1 + PUSH_PER_S * u : 1;
    m.panX = moving ? Math.cos(ang) * PAN_PX_S * k * u : 0; m.panY = moving ? Math.sin(ang) * PAN_PX_S * k * u : 0;
    const run = M.time(8, 3) + 3 * beat / 4;              // the hit after the near-silence (8.3.4)
    if (c.still) {
      await c.still.draw(g, B);
    } else if (c.shot === 'TERM') {
      // idle until the hit (cursor on for the first half of every beat), then a new log line on every beat
      // a new log line on every 8th once it runs (the drop's own pulse); the cursor blinks on the beat while idle
      const sinceRun = t - run, lines = sinceRun < 0 ? 0 : 1 + Math.floor(sinceRun / (beat / 2) + 1e-6);
      const ph = sinceRun < 0 ? (((t - c.t) / beat) % 1) : ((sinceRun / (beat / 2)) % 1);
      T().terminal(g, { scroll: lines, cursor: ph < 0.5 });
    } else if (c.shot === 'DRAIN') {
      const p = Motion.ease.inOut(Math.min(1, (u + 1 / FPS) / beat));
      T().grid(g); T().inkMark(g);
      T().terminal(g, { scroll: 1 + Math.floor((c.t - run) / (beat / 2) + 1e-6), cursor: false, level: H * p });
    } else if (c.shot === 'END1') {
      T().grid(g); T().inkMark(g);
    } else if (c.shot === 'END2') {
      T().grid(g); T().inkMark(g); T().url(g, ((u / beat) % 2) < 1);
    } else if (c.shot === 'END3') {
      T().grid(g); m.push = 1; m.u = 0; m.panX = 0; m.panY = 0; await tinInside(); T().url(g, true);
    }
    m.push = 1; m.u = 0; m.drift = 0; m.panX = 0; m.panY = 0;
    for (const [a, b, text] of WORDS) if (f >= frameOf(pos(a)) && f < frameOf(pos(b))) words(text);
    B.drawGrain(g, 0.07, f);
  } finally { g.restore(); }
};
window.EDIT_CUTS = CUTS;
window.EDIT_WORDS = WORDS.map(([a, b, text]) => ({ from: a, to: b, text, t: pos(a), tEnd: pos(b) }));
// Live preview for a person opening this page in a browser (never in render mode, which passes ?render=1): click to
// play the cut music and loop the film from its clock. Rendering never touches this path.
if (!new URLSearchParams(location.search).has('render')) {
  document.addEventListener('click', () => {
    if (window.__playing) return; window.__playing = true;
    const a = new Audio('../music-cut/music.wav'); a.loop = true; a.play();
    const step = async () => { await window.seek(a.currentTime % M.cue.length); requestAnimationFrame(step); };
    requestAnimationFrame(step);
  });
}
ready = (async () => {
  await Promise.all(['500 40px "Funktional Grotesk"', '400 40px "Funktional Grotesk"', '500 40px "SF Mono"', '400 40px "Liberation Sans"', '700 40px "Liberation Sans"'].map(s => document.fonts.load(s)));
  const used = new Set(CUTS.map(c => c.shot));
  await Promise.all(window.STILLS.filter(s => used.has(s.label)).flatMap(x => (x.images || []).map(B.img)));
  window.FILM = { duration: M.cue.length, width: W, height: H, fps: FPS };
})();
})();
